/* Live cross-cuts — the same task data, re-sliced by section or by worker    */
/* -------------------------------------------------------------------------- */

export interface LiveTask {
  containerId: string;
  containerTypeCode: string;
  section: SectionKind;
  task: MockTask;
}

/** Every task in a given section, across every container, worker assignments
 * and all — the "stage-wise" live view. */
export function tasksBySection(containers: MockContainer[], kind: SectionKind): LiveTask[] {
  const rows: LiveTask[] = [];
  for (const c of containers) {
    const section = c.sections.find((s) => s.kind === kind);
    if (!section) continue;
    for (const task of section.tasks) {
      rows.push({ containerId: c.id, containerTypeCode: c.typeCode, section: kind, task });
    }
  }
  return rows;
}

/** Every task assigned to one worker, across every container and section —
 * the "crew-wise" live view. Running tasks first, then pending, then settled
 * (done/N-A), each group newest-first isn't tracked so insertion order
 * stands in for it. */
export function tasksForWorker(containers: MockContainer[], workerId: string): LiveTask[] {
  const rows: LiveTask[] = [];
  for (const c of containers) {
    for (const section of c.sections) {
      for (const task of section.tasks) {
        if (task.workerId === workerId) {
          rows.push({ containerId: c.id, containerTypeCode: c.typeCode, section: section.kind, task });
        }
      }
    }
  }
  const rank = (t: LiveTask): number => (t.task.state === 'running' ? 0 : t.task.state === 'pending' ? 1 : 2);
  return [...rows].sort((a, b) => rank(a) - rank(b));
}

export interface CrewLoad {
  worker: MockWorker;
  running: LiveTask[];
  pending: LiveTask[];
  doneToday: LiveTask[];
}

/** One row per worker, their tasks already split by state — what the "by
 * crew" live view and the worker detail record are both built from. */
export function crewLoad(containers: MockContainer[], workers: MockWorker[]): CrewLoad[] {
  return workers.map((worker) => {
    const tasks = tasksForWorker(containers, worker.id);
    return {
      worker,
      running: tasks.filter((t) => t.task.state === 'running'),
      pending: tasks.filter((t) => t.task.state === 'pending'),
      doneToday: tasks.filter((t) => t.task.state === 'done'),
    };
  });
}

/** Active workers with nothing running and nothing scheduled for today —
 * the admin's "who can I actually hand new work to right now" list. Scoped
 * to today specifically rather than "zero pending ever": a worker with next
 * week's tasks already lined up isn't idle today just because nothing of
 * theirs happens to be running this literal second. */
export function idleWorkersToday(containers: MockContainer[], workers: MockWorker[]): MockWorker[] {
  const today = offsetDate(0);
  return workers.filter((w) => {
    if (!w.active) return false;
    const tasks = tasksForWorker(containers, w.id);
    return !tasks.some((t) => t.task.state === 'running' || isScheduledFor(t.task, today));
  });
}

export interface WorkerCompletion {
  worker: MockWorker;
  completedCount: number;
}

/** Tasks a worker actually finished in the last `days` days, by
 * `completedAt` (a point in time, unlike `elapsedSec`'s duration) — ranked,
 * so comparing the whole crew's recent output doesn't mean opening every
 * worker's own detail drawer one at a time. Workers with zero completions
 * in the window are left out rather than padding the list with zeroes. */
export function topPerformers(containers: MockContainer[], workers: MockWorker[], days: number, nowMs: number = Date.now()): WorkerCompletion[] {
  const cutoffMs = nowMs - days * 24 * 60 * 60 * 1000;
  return workers
    .map((worker) => {
      const completedCount = tasksForWorker(containers, worker.id).filter((t) => {
        if (!t.task.completedAt) return false;
        const completedMs = new Date(t.task.completedAt).getTime();
        return !Number.isNaN(completedMs) && completedMs >= cutoffMs;
      }).length;
      return { worker, completedCount };
    })
    .filter((w) => w.completedCount > 0)
    .sort((a, b) => b.completedCount - a.completedCount);
}
