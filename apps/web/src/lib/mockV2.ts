export type TaskState = 'pending' | 'running' | 'done' | 'na';

export interface MockTask {
  key: string;
  label: string;
  workerId: string | null;
  state: TaskState;
  /** Epoch ms the running timer started at; null unless state === 'running'. */
  startedAt: number | null;
  /** Accumulated seconds once stopped. */
  elapsedSec: number;
  /** ISO timestamp set the moment the task is stopped or marked N/A —
   * absent/undefined on tasks that aren't settled yet, and left unset on the
   * hand-authored mock containers below (we don't actually know when those
   * historically finished). Drives time-bounded stats (worker hours this
   * week/month, per-section turnaround) that `elapsedSec` alone can't
   * answer since it's a duration, not a point in time. */
  completedAt?: string | null;
  /** Can be marked Not Applicable instead of timed — e.g. the 2nd paint coat. */
  optional?: boolean;
  /** Average expected duration, for the dashboard's section-load panel. */
  estHrs: number;
  /** Where the container has to physically be to do this task. Fixed by
   * section for Painting/PTI/Cleaning, and for a Repairment task generated
   * from a flagged checklist item (repairTasksFor); null until the Admin
   * picks one for a genuinely ad-hoc Repairment task with no checklist item
   * behind it. */
  site: SailingSite | null;
  /** Overrides the section's default assignee type (SECTION_OWNER_TYPE) for
   * this one task — e.g. Painting's tape/compressor tasks go to a Painter
   * Helper, not the Painter who does Primer/coats/Logo (SPEC.md §4.3). */
  ownerType?: WorkerType;
  /** Explicit task keys (within the same section) this one waits on. When
   * set, this replaces plain array-order for sequencing — lets two tasks
   * that both only depend on an earlier step (e.g. Logo and painting the
   * compressor/display, both only gated on the main coats being done) run
   * in parallel instead of blocking each other. Tasks without this still
   * fall back to strict array order (paintingTaskBlockedBy below). */
  dependsOn?: string[];
  /** A plain 'YYYY-MM-DD' date — which day this task is actually planned
   * for, separate from whether it's been worked yet. Absent/undefined means
   * unscheduled: assigning a worker (v2Store's assignWorker) fills this in
   * with today unless it's already set, same "optional, filled in as it
   * becomes known" shape as completedAt above — a task generated by intake
   * or by the demo data never has to carry a fabricated date it doesn't
   * actually have yet. */
  scheduledFor?: string | null;
}

