/** "Today"/"Tomorrow" read faster than a raw date for the only two days most
 * planning actually happens on; anything further out just shows the date. */
export function scheduleLabel(date: string | null | undefined): string {
  if (!date) return 'Unscheduled';
  if (date === offsetDate(0)) return 'Today';
  if (date === offsetDate(1)) return 'Tomorrow';
  return date;
}

/** Painting only (SPEC.md §4.3): Primer → 1st coat → 2nd coat → Logo run in a
 * fixed order, unlike every other section's tasks. Returns the earliest task
 * still holding this one up, or null if it's clear to start.
 *
 * Walks the *whole* ancestor chain, not just the immediate dependency —
 * a dependency counting as "settled" (done, or marked N/A as skipped) says
 * nothing about whether its own dependency was ever actually satisfied. An
 * optional step can be marked N/A the moment it's reachable, independent of
 * whether the step before *it* has finished; checking only one level would
 * report Logo as clear to start the instant 2nd coat is marked N/A, even
 * while 1st coat is still running underneath it. */
export function paintingTaskBlockedBy(section: MockSection, task: MockTask): MockTask | null {
  if (section.kind !== 'painting') return null;
  const deps: MockTask[] = task.dependsOn
    ? task.dependsOn.map((key) => section.tasks.find((t) => t.key === key)).filter((t): t is MockTask => Boolean(t))
    : section.tasks.slice(0, section.tasks.findIndex((t) => t.key === task.key));
  for (const dep of deps) {
    if (!taskSettled(dep)) return dep;
    const upstream = paintingTaskBlockedBy(section, dep);
    if (upstream) return upstream;
  }
  return null;
}

export function sectionStatus(section: MockSection): Status {
  const total = section.tasks.length;
  const settled = section.tasks.filter(taskSettled).length;
  const running_ = section.tasks.some((t) => t.state === 'running');
  if (total > 0 && settled === total) {
    return { tone: 'ok', icon: 'check-circle', label: 'Done', detail: `${SECTION_LABELS[section.kind]}: every task complete.` };
  }
  if (running_) {
    return { tone: 'info', icon: 'clock', label: `${settled}/${total}`, detail: `${SECTION_LABELS[section.kind]}: a task is running now, ${settled} of ${total} complete.` };
  }
  if (settled > 0) {
    return { tone: 'warn', icon: 'clock', label: `${settled}/${total}`, detail: `${SECTION_LABELS[section.kind]}: ${settled} of ${total} tasks complete, none running.` };
  }
  return { tone: 'neutral', icon: 'clock', label: `0/${total}`, detail: `${SECTION_LABELS[section.kind]}: not started.` };
}

export function isReadyToMove(container: MockContainer): boolean {
  if (!container.survey) return false;
  if (container.survey.outcome === 'ready') return true;
  if (container.sections.length === 0) return false;
  // A section with no tasks yet isn't "done" — it's unactioned. Without this,
  // `[].every(...)` is vacuously true and a section that was flagged but
  // never given a task would count as complete.
  return container.sections.every((s) => s.tasks.length > 0 && s.tasks.every(taskSettled));
}

/** Days since this container last moved stage — gate-in (`registeredAt`) if
 * it hasn't been surveyed yet, otherwise the survey date. Zero once it's
 * ready, since aging stops mattering the moment there's nothing left
 * waiting. Thresholds (3d warn, 7d bad) are a starting guess, not a number
 * from the depot — tune freely. */
export function agingDays(container: MockContainer, nowMs: number = Date.now()): number {
  if (container.readyAt) return 0;
  const baseline = container.survey ? container.survey.performedAt : container.registeredAt;
  const baselineMs = new Date(baseline).getTime();
  if (Number.isNaN(baselineMs)) return 0;
  return Math.max(0, Math.floor((nowMs - baselineMs) / (1000 * 60 * 60 * 24)));
}

/** Null when there's nothing to flag — under the warn threshold, or already
 * ready to move. */
export function agingStatus(container: MockContainer): Status | null {
  const days = agingDays(container);
  if (days < 3) return null;
  const tone: StatusTone = days >= 7 ? 'bad' : 'warn';
  const stage = container.survey ? 'in progress' : 'awaiting survey';
  return { tone, icon: 'clock', label: `${days}d ${stage}`, detail: `${container.id} has been ${stage} for ${days} day(s).` };
}

export function isDeparted(container: MockContainer): boolean {
  return container.departedAt !== null;
}

export function overallStatus(container: MockContainer): Status {
  if (container.departedAt) {
    return { tone: 'neutral', icon: 'truck', label: 'Departed', detail: `${container.id} gated out on ${formatSurveyDate(container.departedAt)}.` };
  }
  if (container.readyAt || isReadyToMove(container)) {
    return { tone: 'ok', icon: 'check-circle', label: 'Ready to move', detail: `${container.id} has cleared every required section.` };
  }
  if (!container.survey) {
    return { tone: 'neutral', icon: 'doc', label: 'Awaiting survey', detail: `${container.id} has not been surveyed yet.` };
  }
  const anyRunning = container.sections.some((s) => s.tasks.some((t) => t.state === 'running'));
  return {
    tone: anyRunning ? 'info' : 'warn',
    icon: 'clock',
    label: anyRunning ? 'In progress' : 'Open',
    detail: `${container.id} has open work in ${container.sections.length} section(s).`,
  };
}

export function openTaskCount(container: MockContainer): number {
  return container.sections.reduce((n, s) => n + s.tasks.filter((t) => !taskSettled(t)).length, 0);
}

export interface PtiBreakdown {
  total: number;
  ptiPending: number;
  lightsPendingOnly: number;
  curtainPendingOnly: number;
  fullyOk: number;
}

export function ptiBreakdown(containers: MockContainer[]): PtiBreakdown {
  let ptiPending = 0;
  let lightsPendingOnly = 0;
  let curtainPendingOnly = 0;
  let fullyOk = 0;
  for (const c of containers) {
    const pti = c.sections.find((s) => s.kind === 'pti');
    if (!pti) {
      fullyOk += 1;
      continue;
    }
    const lights = pti.tasks.find((t) => t.key === 'lights');
    const strip = pti.tasks.find((t) => t.key === 'strip_curtain');
    const lightsDone = !lights || taskSettled(lights);
    const stripDone = !strip || taskSettled(strip);
    if (!lightsDone && !stripDone) ptiPending += 1;
    else if (!lightsDone && stripDone) lightsPendingOnly += 1;
    else if (lightsDone && !stripDone) curtainPendingOnly += 1;
    else fullyOk += 1;
  }
  return { total: containers.length, ptiPending, lightsPendingOnly, curtainPendingOnly, fullyOk };
}

export interface SectionLoad {
  kind: SectionKind;
  pendingTasks: number;
  avgEstHrs: number;
}

export function sectionLoad(containers: MockContainer[]): SectionLoad[] {
  const kinds: SectionKind[] = ['painting', 'pti', 'cleaning', 'all_rounder', 'sailing'];
  return kinds.map((kind) => {
    const openTasks = containers
      .flatMap((c) => c.sections.filter((s) => s.kind === kind))
      .flatMap((s) => s.tasks)
      .filter((t) => !taskSettled(t));
    const avg = openTasks.length ? openTasks.reduce((sum, t) => sum + t.estHrs, 0) / openTasks.length : 0;
    return { kind, pendingTasks: openTasks.length, avgEstHrs: Math.round(avg * 10) / 10 };
  });
}

export interface SectionContainerCounts {
  kind: SectionKind;
  /** Container has a task actively running in this section right now. */
  inProcess: number;
  /** Container has this section, nothing running, not fully settled yet —
   * i.e. still waiting its turn. */
  inLine: number;
  /** Every task in this section is done or N/A. */
  done: number;
}

/** How many containers sit at each stage, not how many tasks — the "how many
 * are in process vs. still in line" breakdown for the admin's overview. */
export function sectionContainerCounts(containers: MockContainer[]): SectionContainerCounts[] {
  const kinds: SectionKind[] = ['painting', 'pti', 'cleaning', 'all_rounder', 'sailing'];
  return kinds.map((kind) => {
    let inProcess = 0;
    let inLine = 0;
    let done = 0;
    for (const c of containers) {
      const section = c.sections.find((s) => s.kind === kind);
      if (!section || section.tasks.length === 0) continue;
      if (section.tasks.some((t) => t.state === 'running')) inProcess += 1;
      else if (section.tasks.every(taskSettled)) done += 1;
      else inLine += 1;
    }
    return { kind, inProcess, inLine, done };
  });
}

export interface SectionTurnaround {
  kind: SectionKind;
  completedCount: number;
  avgHrs: number;
}

/** Average *actual* time a completed task in each section took
 * (`elapsedSec`, not the `estHrs` guess) — the yard report's "how long does
 * this really take" number. */
export function sectionTurnaround(containers: MockContainer[]): SectionTurnaround[] {
  const kinds: SectionKind[] = ['painting', 'pti', 'cleaning', 'all_rounder', 'sailing'];
  return kinds.map((kind) => {
    const doneTasks = containers
      .flatMap((c) => c.sections.filter((s) => s.kind === kind))
      .flatMap((s) => s.tasks)
      .filter((t) => t.state === 'done');
    const avgHrs = doneTasks.length ? doneTasks.reduce((sum, t) => sum + t.elapsedSec, 0) / doneTasks.length / 3600 : 0;
    return { kind, completedCount: doneTasks.length, avgHrs: Math.round(avgHrs * 10) / 10 };
  });
}

export interface GateActivity {
  gatedInToday: number;
  gatedOutToday: number;
}

/** How many containers crossed the gate today, specifically — reads
 * `registeredAt`/`departedAt` (always set on every container) rather than
 * `gateIn`/`gateOut` (the detailed form record, which stays null for
 * anything not registered through the live Gate-In form, including most of
 * today's seed data), so this reflects real activity even before any
 * container has gone through that form. */
export function gateActivityToday(containers: MockContainer[]): GateActivity {
  const today = offsetDate(0);
  return {
    gatedInToday: containers.filter((c) => c.registeredAt.slice(0, 10) === today).length,
    gatedOutToday: containers.filter((c) => c.departedAt?.slice(0, 10) === today).length,
  };
}

function parseBudget(estBudget: string | undefined): number | null {
  if (!estBudget) return null;
  const digits = estBudget.replace(/[^0-9.]/g, '');
  const n = Number(digits);
  return digits !== '' && Number.isFinite(n) ? n : null;
}

export interface BudgetExposure {
  /** How many active containers actually carry a parseable estimate — the
   * free-text `estBudget` field is often left blank, and it only exists at
   * all on containers that went through the live Gate-In form (`gateIn`),
   * so this is never assumed to be every container in the yard. */
  estimatedCount: number;
  totalInProgress: number;
  totalReady: number;
}

/** Live cost exposure across the yard, split by whether the container has
 * already cleared its work — the in-progress total is money still being
 * spent, the ready total is money already spent sitting in the yard waiting
 * on gate-out. Reads only the admin's own `gateIn.estBudget` estimate,
 * never invented or defaulted for containers that don't have one. */
export function budgetExposure(containers: MockContainer[]): BudgetExposure {
  let estimatedCount = 0;
  let totalInProgress = 0;
  let totalReady = 0;
  for (const c of containers) {
    const amount = parseBudget(c.gateIn?.estBudget);
    if (amount === null) continue;
    estimatedCount += 1;
    if (c.readyAt || isReadyToMove(c)) totalReady += amount;
    else totalInProgress += amount;
  }
  return { estimatedCount, totalInProgress, totalReady };
}

export interface ReadyNotGatedOut {
  container: MockContainer;
  daysSinceReady: number;
}

/** A container stops "aging" the moment it's ready (`agingDays` zeroes out
 * right then) — which is correct for "is anyone behind on work," but it
 * means nothing currently measures the *next* gap: cleared for release, yet
 * still occupying yard space until someone actually gates it out. */
export function readyNotGatedOut(containers: MockContainer[], nowMs: number = Date.now()): ReadyNotGatedOut[] {
  return containers
    .filter((c) => (c.readyAt || isReadyToMove(c)) && !c.gateOut && !c.departedAt)
    .map((c) => {
      const baselineMs = c.readyAt ? new Date(c.readyAt).getTime() : nowMs;
      const daysSinceReady = Number.isNaN(baselineMs) ? 0 : Math.max(0, Math.floor((nowMs - baselineMs) / (1000 * 60 * 60 * 24)));
      return { container: c, daysSinceReady };
    })
    .sort((a, b) => b.daysSinceReady - a.daysSinceReady);
}

